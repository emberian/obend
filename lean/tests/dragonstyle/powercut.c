/* Hosted, process-reset NVMe model. Only media and the external observer are
 * MAP_SHARED. Each invocation starts in a new process with empty volatile state. */
#define _GNU_SOURCE
#include <assert.h>
#include <stdbool.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <signal.h>
#include <sys/mman.h>
#include <sys/resource.h>
#include <sys/wait.h>
#include <unistd.h>

enum { N = 8, SECTOR = 512, MAX_BODY = 99, CELLS = 4, CUT_EXIT = 77 };
typedef uint8_t sector[SECTOR];
struct media { sector ctrl, wal[N][2]; };
struct observer { unsigned issues[256], replies, authorization_checks; uint8_t generation, body[100]; };
struct shared { struct media disk; struct observer seen; };
static struct shared *world;

struct ring { uint64_t head, tail; uint16_t slots[CELLS]; };
static void put(struct ring *q, uint16_t id) {
    assert(q->tail - q->head < CELLS);
    q->slots[q->tail++ % CELLS] = id;
}
static uint16_t get(struct ring *q) {
    assert(q->tail != q->head);
    return q->slots[q->head++ % CELLS];
}
struct lease { uint16_t owner, slot; uint64_t epoch, generation; };
static bool valid(struct lease a, struct lease b) {
    return a.owner == b.owner && a.slot == b.slot && a.epoch == b.epoch &&
        a.generation == b.generation;
}
static bool recycle(struct lease *l) {
    if (l->generation < UINT64_MAX) { ++l->generation; return true; }
    if (l->epoch == UINT64_MAX) return false;
    ++l->epoch; l->generation = 0; return true;
}

enum cut { NORMAL, DMA, FLUSHED, FUA_OLD, FUA_NEW, DISPATCHED, SENT, EIO_WAL, EIO_FLUSH, EIO_FUA, EIO_FUA_NEW };
struct fault { enum cut cut; int first; unsigned bytes; };
static struct fault fault;
static struct ring rx, rx_free, storage, storage_free, tx, tx_free;
static sector cache[2];
static uint8_t tickets[N][100];
static uint8_t state[2 + 100*N], scratch[8+MAX_BODY];
static unsigned phase;
static bool cached[2];
static bool booted;

extern uint32_t turnIntake(uintptr_t, uint64_t, uintptr_t, uintptr_t);
extern uint32_t parseFrame(uintptr_t, uint64_t);
extern void *cml_heap, *cml_stack, *cml_stackend;
extern void cml_main(void);
void cml_clear(void) {}
void *cml_install(uint8_t *src, size_t n, uint8_t *dst) {
    (void)src; (void)n; (void)dst; abort();
}
void cml_err(int code) { (void)code; abort(); }
extern void *__real_malloc(size_t), *__real_calloc(size_t,size_t), *__real_realloc(void*,size_t);
void *__wrap_malloc(size_t n) { if (booted) abort(); return __real_malloc(n); }
void *__wrap_calloc(size_t a, size_t b) { if (booted) abort(); return __real_calloc(a,b); }
void *__wrap_realloc(void *p, size_t n) { if (booted) abort(); return __real_realloc(p,n); }

/* Little-endian header. The full block is a single aligned logical sector on
 * this device (AWUPF = 0, one LBA). The two WAL sectors have independent fate. */
static void encode(sector dst, unsigned generation) {
    memset(dst,0,SECTOR);
    dst[0] = (uint8_t)generation;
    for (int i = 0; i < 8; ++i) dst[8+i] = (uint8_t)~dst[i];
    uint32_t crc = UINT32_MAX;
    for (int i=0; i<16; ++i) {
        crc ^= dst[i];
        for (int bit=0; bit<8; ++bit) crc = (crc>>1) ^ ((crc&1) ? UINT32_C(0x82f63b78) : 0);
    }
    crc ^= UINT32_MAX;
    for (int i=0; i<4; ++i) dst[16+i] = (uint8_t)(crc>>(8*i));
}
static bool cold(uint8_t *view, uint8_t principal) {
    const struct media *d = &world->disk;
    unsigned g = d->ctrl[0];
    sector expected;
    encode(expected,g);
    if (g > N || memcmp(d->ctrl,expected,SECTOR)) return false;
    view[0] = g;
    view[1] = principal;
    for (unsigned i=0; i<g; ++i) {
        const uint8_t *meta = d->wal[i][0];
        if (meta[0] < 10 || meta[0] > MAX_BODY) return false;
        uint8_t *entry = view + 2 + 100*i;
        memcpy(entry,meta,5);
        memcpy(entry+5,d->wal[i][1],meta[0]-4);
    }
    return true;
}
static void cut_at(enum cut point) { if (fault.cut == point) _exit(CUT_EXIT); }
static void control(const uint8_t *body, size_t n, uint8_t *ctrl, size_t size) {
    assert(body == scratch+8 && n >= 10 && n <= MAX_BODY);
    assert(ctrl == scratch && size == 8 && ctrl[0] == 255);
}

/* The verifier-private table is generated by running the real Powerbox and
 * IrreversibleOutbox gates over successive reachable Simplex views. */
void ffiauthorize(uint8_t *body, size_t n, uint8_t *ctrl, size_t size) {
    control(body,n,ctrl,size);
    assert(state[0] < N && phase == 0 && ctrl[1] == state[0]+1);
    ++world->seen.authorization_checks;
    const uint8_t *ticket = tickets[state[0]];
    if (ticket[0] == n && !memcmp(body,ticket+1,n)) ctrl[0] = 0;
}

enum action { REFUSED, METADATA, DATA, BARRIER, COMMIT };
enum opcode { FLUSH, WRITE };
struct command { enum opcode op; uint32_t nsid; uint64_t slba; uint16_t nlb; bool fua; };
static enum action classify(struct command q) {
    if (q.nsid != 1 || q.nlb || state[0] >= N) return REFUSED;
    uint64_t first = 1 + 2*(uint64_t)state[0];
    if (phase == 2 && q.op == WRITE && q.fua && q.slba == 0) return COMMIT;
    if (phase != 1 || q.fua) return REFUSED;
    if (q.op == WRITE && q.slba == first && !cached[0]) return METADATA;
    if (q.op == WRITE && q.slba == first+1 && !cached[1]) return DATA;
    if (q.op == FLUSH && !q.slba && cached[0] && cached[1]) return BARRIER;
    return REFUSED;
}

/* The trusted virtualiser confines all WAL writes to the next two LBAs.
 * Controller completion order is independent of submission order. */
void ffiwal(uint8_t *body, size_t n, uint8_t *ctrl, size_t size) {
    control(body,n,ctrl,size);
    unsigned i = state[0];
    assert(phase == 0 && i < N && ctrl[1] == i+1 && world->disk.ctrl[0] == i);
    if (fault.cut == EIO_WAL) return;
    phase = 1;
    uint16_t pending[2];
    put(&storage,get(&storage_free)); put(&storage,get(&storage_free));
    pending[0] = get(&storage); pending[1] = get(&storage);
    for (unsigned k=0; k<2; ++k) {
        unsigned block = (unsigned)fault.first ^ k;
        struct command q = {WRITE,1,1+2*i+block,0,false};
        assert(classify(q) == (block ? DATA : METADATA));
        if (block == 0) {
            cache[0][0] = (uint8_t)n;
            memcpy(cache[0]+1,body,4);
        } else memcpy(cache[1],body+4,n-4);
        cached[block] = true;
        /* Power may persist a prefix of either sector, or both full sectors,
         * before the caller sees FLUSH completion. */
        unsigned bytes = fault.bytes > k*SECTOR ? fault.bytes - k*SECTOR : 0;
        if (bytes > SECTOR) bytes = SECTOR;
        if (fault.cut == DMA) memcpy(world->disk.wal[i][block],cache[block],bytes);
        put(&storage_free,pending[block]);
    }
    cut_at(DMA);
    ctrl[0] = 0;
}
void ffiflush(uint8_t *body, size_t n, uint8_t *ctrl, size_t size) {
    control(body,n,ctrl,size); assert(classify((struct command){FLUSH,1,0,0,false}) == BARRIER);
    if (fault.cut == EIO_FLUSH) return;
    for (int k=0; k<2; ++k) {
        int block = k ^ fault.first;
        memcpy(world->disk.wal[state[0]][block],cache[block],SECTOR);
    }
    phase = 2; cut_at(FLUSHED); ctrl[0] = 0;
}
void ffifua(uint8_t *body, size_t n, uint8_t *ctrl, size_t size) {
    control(body,n,ctrl,size); assert(classify((struct command){WRITE,1,0,0,true}) == COMMIT);
    cut_at(FUA_OLD);
    if (fault.cut == EIO_FUA) return;
    sector next;
    encode(next,ctrl[1]);
    memcpy(world->disk.ctrl,next,SECTOR);
    phase = 3; cut_at(FUA_NEW);
    if (fault.cut != EIO_FUA_NEW) ctrl[0] = 0;
}
void ffidispatch(uint8_t *body, size_t n, uint8_t *ctrl, size_t size) {
    control(body,n,ctrl,size); assert(phase == 3);
    assert(++world->seen.issues[body[2]] == 1);
    phase = 4; cut_at(DISPATCHED); ctrl[0] = 0;
}
void ffireply(uint8_t *body, size_t n, uint8_t *ctrl, size_t size) {
    control(body,n,ctrl,size);
    assert(phase == 0 || phase == 4);
    uint8_t reader[sizeof(state)] = {0};
    assert(cold(reader,body[0]) && ctrl[1] && ctrl[1] <= reader[0]);
    const uint8_t *entry = reader+2+100*(ctrl[1]-1);
    assert(entry[0] == n && !memcmp(entry+1,body,n));
    put(&tx,get(&tx_free));
    world->seen.body[0] = (uint8_t)n;
    memcpy(world->seen.body+1,body,n);
    world->seen.generation = ctrl[1]; ++world->seen.replies;
    put(&tx_free,get(&tx));
    cut_at(SENT); ctrl[0] = 0;
}

static const char prefix[] = "POST /turn HTTP/1.1\r\nHost: appliance\r\nContent-Length: ";
struct input { uint8_t bytes[180]; size_t n; uint8_t principal; };
static struct input frame(uint8_t principal, uint8_t nonce, uint8_t id, uint8_t charge, unsigned n) {
    struct input r = {.principal = principal};
    assert(n >= 10 && n <= MAX_BODY);
    size_t h = sizeof(prefix)-1;
    memcpy(r.bytes,prefix,h);
    r.bytes[h++] = (uint8_t)('0'+n/10); r.bytes[h++] = (uint8_t)('0'+n%10);
    memcpy(r.bytes+h,"\r\n\r\n",4); h+=4;
    r.bytes[h] = principal; r.bytes[h+1] = nonce; r.bytes[h+2] = id; r.bytes[h+3] = charge;
    for (unsigned j=4; j<n; ++j) r.bytes[h+j] = (uint8_t)(id*13+j*41);
    r.n = h+n;
    return r;
}

struct arena_slot { struct lease owner; size_t used; bool retired; uint8_t data[180]; };
struct borrowed { struct lease lease; size_t offset, length; };
static struct arena_slot slots[CELLS];
static bool parked;

static const uint8_t *resolve(struct borrowed v) {
    if (v.lease.slot >= CELLS) return NULL;
    const struct arena_slot *slot = &slots[v.lease.slot];
    if (slot->retired || !valid(v.lease,slot->owner) || v.offset > slot->used || v.length > slot->used-v.offset)
        return NULL;
    return slot->data+v.offset;
}
static void boot(void) {
    static uint64_t runtime[2 * 1024 * 1024];
    cml_heap = runtime; cml_stack = runtime+1024*1024; cml_stackend = runtime+2*1024*1024;
    cml_main();
    booted = true;
    rx_free.head = rx_free.tail = UINT64_MAX-1;
    for (int i=0; i<CELLS; ++i) {
        slots[i].owner = (struct lease){1,(uint16_t)i,7,UINT64_MAX};
        put(&rx_free,i); put(&storage_free,i); put(&tx_free,i);
    }
}
static unsigned serve(const struct input *req, struct fault f) {
    if (parked || rx_free.head == rx_free.tail || tx_free.head == tx_free.tail) return 0;
    fault = f;
    phase = 0; cached[0] = cached[1] = false;
    if (!cold(state,req->principal)) { parked = true; return 0; }
    unsigned count = (unsigned)(rx_free.tail-rx_free.head);
    while (count && slots[rx_free.slots[rx_free.head % CELLS]].retired) {
        put(&rx_free,get(&rx_free));
        --count;
    }
    if (!count) return 0;
    uint16_t slotId = get(&rx_free);
    struct arena_slot *slot = &slots[slotId];
    if (req->n > sizeof(slot->data)) { put(&rx_free,slotId); return 0; }
    memcpy(slot->data,req->bytes,req->n); /* simulated ingress DMA */
    slot->used = req->n;
    put(&rx,slotId);
    struct borrowed v = {slots[get(&rx)].owner,0,req->n};
    const uint8_t *src = resolve(v);
    assert(src);
    unsigned result = turnIntake((uintptr_t)src,v.length,(uintptr_t)state,(uintptr_t)scratch);
    /* An unobserved completion requires cold recovery before another mutation. */
    if (!result && (phase || f.cut >= EIO_WAL)) parked = true;
    slot->retired = !recycle(&slot->owner);
    put(&rx_free,slotId);
    assert(!resolve(v));
    assert(storage_free.tail-storage_free.head == CELLS && tx_free.tail-tx_free.head == CELLS);
    return result;
}
static unsigned invoke(const struct input *req, struct fault f) {
    pid_t pid = fork();
    assert(pid >= 0);
    if (pid == 0) { boot(); _exit((int)serve(req,f)); }
    int status;
    assert(waitpid(pid,&status,0) == pid && WIFEXITED(status));
    return (unsigned)WEXITSTATUS(status);
}
static void format(void) {
    memset(world,0,sizeof(*world));
    encode(world->disk.ctrl,0);
}
static unsigned scenarios;
static void scenario(struct fault f, const struct shared *base,
                     const struct input *one, const struct input *two) {
    *world = *base;
    const bool installed = f.cut == FUA_NEW || f.cut == EIO_FUA_NEW || f.cut == DISPATCHED || f.cut == SENT;
    unsigned status = invoke(two,f);
    assert(status == (f.cut >= EIO_WAL ? 0 : CUT_EXIT));
    assert(world->disk.ctrl[0] == (installed ? 2 : 1));
    assert(!memcmp(base->disk.wal[0],world->disk.wal[0],2*SECTOR));
    assert(world->seen.replies == 1+(unsigned)(f.cut == SENT));
    assert(world->seen.issues[2] == (unsigned)(f.cut == DISPATCHED || f.cut == SENT));
    assert(invoke(one,(struct fault){0}) == 1);
    assert(invoke(two,(struct fault){0}) == 2);
    assert(invoke(two,(struct fault){0}) == 2);
    assert(world->seen.issues[1] == 1 && world->seen.issues[2] == (unsigned)(f.cut != FUA_NEW && f.cut != EIO_FUA_NEW));
    assert(world->seen.generation == 2 && world->seen.body[0] == 99);
    ++scenarios;
}
/* Exercise each linker trap after runtime boot in its own child. */
static void allocation_canary(int which) {
    pid_t pid = fork();
    assert(pid >= 0);
    if (!pid) {
        struct rlimit no_core = {0,0};
        assert(setrlimit(RLIMIT_CORE,&no_core) == 0);
        boot();
        void *(*volatile m)(size_t) = malloc;
        void *(*volatile c)(size_t,size_t) = calloc;
        void *(*volatile r)(void *,size_t) = realloc;
        void *ptr = which == 0 ? m(8) : which == 1 ? c(1,8) : r(NULL,8);
        _exit(ptr ? 1 : 2);
    }
    int status;
    assert(waitpid(pid,&status,0) == pid && WIFSIGNALED(status) && WTERMSIG(status) == SIGABRT);
}
int main(int argc, char **argv) {
    for (int i=0; i<3; ++i) allocation_canary(i);
    state[0] = 2; phase = 1;
    assert(classify((struct command){WRITE,1,0,0,true}) == REFUSED);
    assert(classify((struct command){WRITE,1,3,0,false}) == REFUSED);
    assert(classify((struct command){WRITE,2,5,0,false}) == REFUSED);
    assert(classify((struct command){WRITE,1,5,1,false}) == REFUSED);
    assert(classify((struct command){FLUSH,1,0,0,false}) == REFUSED);
    phase = 0;
    assert(argc == 2);
    FILE *file = fopen(argv[1],"rb");
    assert(file && fread(tickets,1,sizeof(tickets),file) == sizeof(tickets));
    for (unsigned i=0; i<=N; ++i) {
        uint8_t crc[4];
        sector header;
        encode(header,i);
        assert(fread(crc,1,sizeof(crc),file) == sizeof(crc) && !memcmp(header+16,crc,sizeof(crc)));
    }
    assert(fgetc(file) == EOF && fclose(file) == 0);
    world = mmap(NULL,sizeof(*world),PROT_READ|PROT_WRITE,MAP_SHARED|MAP_ANONYMOUS,-1,0);
    assert(world != MAP_FAILED);
    format();
    struct input one = frame(1,17,1,8,10), two = frame(1,31,2,12,99);
    assert(invoke(&one,(struct fault){0}) == 1);
    struct shared base = *world;
    struct input forged=two;
    forged.bytes[forged.n-1] ^= 1;
    assert(!invoke(&forged,(struct fault){0}));
    assert(world->seen.authorization_checks == base.seen.authorization_checks+1);
    assert(!memcmp(&base.disk,&world->disk,sizeof(base.disk)));
    for (int order=0; order<2; ++order) {
        for (unsigned bytes=0; bytes<=2*SECTOR; ++bytes)
            scenario((struct fault){DMA,order,bytes},&base,&one,&two);
        for (enum cut c=FLUSHED; c<=EIO_FUA_NEW; ++c)
            scenario((struct fault){c,order,0},&base,&one,&two);
    }
    struct shared full = *world;
    struct input conflict=two, over=frame(1,88,3,1,19), duplicate=frame(2,44,2,1,15);
    conflict.bytes[conflict.n-1] ^= 1;
    assert(!invoke(&conflict,(struct fault){0}) && !invoke(&over,(struct fault){0}));
    assert(!invoke(&duplicate,(struct fault){0}));
    two.principal=2; assert(!invoke(&two,(struct fault){0})); two.principal=1;
    for (size_t i=0; i<two.n-99; ++i) {
        struct input bad=two; bad.bytes[i] ^= 128;
        assert(!invoke(&bad,(struct fault){0}));
    }
    --two.n; assert(!invoke(&two,(struct fault){0})); ++two.n;
    assert(!memcmp(&full,world,sizeof(full)));
    for (unsigned i=3; i<=N; ++i) {
        struct input r=frame(2,i,i,1,30);
        assert(invoke(&r,(struct fault){0}) == i);
    }
    struct input excess=frame(2,99,99,1,10);
    assert(!invoke(&excess,(struct fault){0}));
    assert(invoke(&one,(struct fault){0}) == 1);
    pid_t warm = fork();
    assert(warm >= 0);
    if (warm == 0) {
        format(); boot();
        assert(serve(&one,(struct fault){0}) == 1);
        for (int i=0; i<12; ++i) assert(serve(&one,(struct fault){0}) == 1);
        assert(!serve(&two,(struct fault){EIO_FUA_NEW,0,0}));
        assert(!serve(&two,(struct fault){0}) && parked && world->disk.ctrl[0] == 2);
        _exit(0);
    }
    int warmStatus;
    assert(waitpid(warm,&warmStatus,0) == warm && WIFEXITED(warmStatus) && !WEXITSTATUS(warmStatus));
    assert(invoke(&two,(struct fault){0}) == 2 && world->seen.issues[2] == 0);
    uint8_t view[sizeof(state)];
    world->disk.ctrl[8] ^= 1;
    assert(!cold(view,1));
    world->disk.ctrl[8] ^= 1;
    world->disk.ctrl[0] ^= 1; world->disk.ctrl[8] ^= 1; /* coherent complement, bad CRC */
    assert(!cold(view,1));
    struct lease last={1,0,UINT64_MAX,UINT64_MAX};
    assert(!recycle(&last));
    printf("%u fault schedules passed; all TX receipts recovered; no duplicate dispatch or post-boot wrapped allocations\n",scenarios);
    return 0;
}
